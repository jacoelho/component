// Command genmap writes map_gen.go: the Map, MapValue and MapContext
// constructors for one to eight inputs. Run it with go generate.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

const maxArity = 8

var counts = [...]string{"", "one input", "two inputs", "three inputs", "four inputs",
	"five inputs", "six inputs", "seven inputs", "eight inputs"}

type form struct {
	name    string // MapValue, Map or MapContext
	doc     string
	context bool
	fails   bool
}

var forms = []form{
	{name: "MapValue", doc: "fn cannot fail."},
	{name: "Map", doc: "fn may fail.", fails: true},
	{name: "MapContext", doc: "fn receives the context given to New and may fail.", context: true, fails: true},
}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/genmap; DO NOT EDIT.\n\npackage component\n\nimport \"context\"\n")
	for n := 1; n <= maxArity; n++ {
		for _, f := range forms {
			write(&b, f, n)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile("map_gen.go", src, 0o600); err != nil {
		log.Fatalf("write map_gen.go: %v", err)
	}
}

func write(b *bytes.Buffer, f form, n int) {
	name := f.name
	if n > 1 {
		name = fmt.Sprintf("%s%d", f.name, n)
	}
	types := make([]string, n)
	params := make([]string, n)
	edges := make([]string, n)
	args := make([]string, n)
	for i := range n {
		t := string(rune('A' + i))
		p := strings.ToLower(t)
		types[i] = t
		params[i] = fmt.Sprintf("%s In[%s]", p, t)
		edges[i] = fmt.Sprintf("edgeOf(%s)", p)
		args[i] = fmt.Sprintf("as[%s](args[%d])", t, i)
	}
	fnParams := strings.Join(types, ", ")
	callArgs := strings.Join(args, ", ")
	ctxParam := "_"
	if f.context {
		fnParams = "context.Context, " + fnParams
		callArgs = "ctx, " + callArgs
		ctxParam = "ctx"
	}
	result, body := "R", fmt.Sprintf("return fn(%s), nil", callArgs)
	if f.fails {
		result, body = "(R, error)", fmt.Sprintf("return fn(%s)", callArgs)
	}
	fmt.Fprintf(b, "\n// %s declares a node built by fn from %s, given in fn's argument order.\n// %s\n", name, counts[n], f.doc)
	fmt.Fprintf(b, "func %s[R, %s any](%s, fn func(%s) %s, opts ...Option[R]) Ref[R] {\n",
		name, strings.Join(types, ", "), strings.Join(params, ", "), fnParams, result)
	fmt.Fprintf(b, "\tinputs := []edge{%s}\n", strings.Join(edges, ", "))
	fmt.Fprintf(b, "\tif fn == nil {\n\t\treturn invalid(%q, inputs, opts)\n\t}\n", name)
	fmt.Fprintf(b, "\treturn declare(funcLabel(fn), inputs, func(%s context.Context, args []any) (R, error) {\n\t\t%s\n\t}, opts)\n}\n",
		ctxParam, body)
}
